#!/usr/bin/env python3
"""Keccak-256 reference and test vectors for keccak256_core.v (V0.6).

The reference permutation is checked twice before any vector is written:
against Python's hashlib.sha3_256 (same permutation, NIST padding 0x06) and
against known Ethereum Keccak-256 values (padding 0x01).

    python3 gen_keccak_vectors.py .      # writes tb_keccak_vecs.vh
"""
import hashlib
import os
import sys

RC = [0x0000000000000001, 0x0000000000008082, 0x800000000000808A, 0x8000000080008000,
      0x000000000000808B, 0x0000000080000001, 0x8000000080008081, 0x8000000000008009,
      0x000000000000008A, 0x0000000000000088, 0x0000000080008009, 0x000000008000000A,
      0x000000008000808B, 0x800000000000008B, 0x8000000000008089, 0x8000000000008003,
      0x8000000000008002, 0x8000000000000080, 0x000000000000800A, 0x800000008000000A,
      0x8000000080008081, 0x8000000000008080, 0x0000000080000001, 0x8000000080008008]
ROT = [[0, 36, 3, 41, 18], [1, 44, 10, 45, 2], [62, 6, 43, 15, 61], [28, 55, 25, 21, 56], [27, 20, 39, 8, 14]]
M64 = (1 << 64) - 1
RATE = 136


def rotl(v, n):
    return ((v << n) | (v >> (64 - n))) & M64 if n else v


def keccak_f(A):
    for r in range(24):
        C = [A[x][0] ^ A[x][1] ^ A[x][2] ^ A[x][3] ^ A[x][4] for x in range(5)]
        D = [C[(x - 1) % 5] ^ rotl(C[(x + 1) % 5], 1) for x in range(5)]
        A = [[A[x][y] ^ D[x] for y in range(5)] for x in range(5)]
        B = [[0] * 5 for _ in range(5)]
        for x in range(5):
            for y in range(5):
                B[y][(2 * x + 3 * y) % 5] = rotl(A[x][y], ROT[x][y])
        A = [[B[x][y] ^ (~B[(x + 1) % 5][y] & B[(x + 2) % 5][y]) for y in range(5)] for x in range(5)]
        A[0][0] ^= RC[r]
    return A


def pad(msg, dsbyte):
    p = bytearray(msg) + bytes([dsbyte])
    p += bytes((-len(p)) % RATE)
    p[-1] |= 0x80
    return bytes(p)


def sponge(msg, dsbyte):
    A = [[0] * 5 for _ in range(5)]
    p = pad(msg, dsbyte)
    for off in range(0, len(p), RATE):
        blk = p[off:off + RATE]
        for i in range(RATE // 8):
            A[i % 5][i // 5] ^= int.from_bytes(blk[8 * i:8 * i + 8], "little")
        A = keccak_f(A)
    return b"".join(A[i % 5][i // 5].to_bytes(8, "little") for i in range(4))


def keccak256(msg):
    return sponge(msg, 0x01)


def selfcheck():
    for m in (b"", b"abc", bytes(range(200)), b"x" * 135, b"x" * 136):
        assert sponge(m, 0x06) == hashlib.sha3_256(m).digest(), "permutation disagrees with hashlib"
    assert keccak256(b"").hex() == "c5d2460186f7233c927e7db2dcc703c0e500b653ca82273b7bfad8045d85a470"
    assert keccak256(b"transfer(address,uint256)")[:4].hex() == "a9059cbb"


MESSAGES = [b"", b"abc", b"transfer(address,uint256)", bytes(range(55)), b"\xa5" * 135, b"\x00" * 136,
            bytes(range(137)), bytes((7 * i) & 0xFF for i in range(300)),
            b"".join(hashlib.sha256(bytes([i])).digest() for i in range(16))[:500]]


def main(outdir):
    selfcheck()
    blocks, plan = [], []
    for m in MESSAGES:
        p = pad(m, 0x01)
        plan.append((len(blocks), len(p) // RATE, keccak256(m)))
        blocks += [p[o:o + RATE] for o in range(0, len(p), RATE)]
    lines = ["// generated by gen_keccak_vectors.py: Keccak-256 (padding 0x01), blocks big-endian",
             "localparam NVEC = %d;" % len(plan), "localparam NBLK = %d;" % len(blocks),
             "reg [1087:0] vblk [0:NBLK-1];", "integer vfirst [0:NVEC-1];", "integer vcount [0:NVEC-1];",
             "reg [255:0] vexp [0:NVEC-1];", "initial begin"]
    for i, b in enumerate(blocks):
        lines.append("    vblk[%d] = 1088'h%s;" % (i, b.hex()))
    for i, (first, n, d) in enumerate(plan):
        lines.append("    vfirst[%d] = %d; vcount[%d] = %d; vexp[%d] = 256'h%s;" % (i, first, i, n, i, d.hex()))
    lines.append("end")
    with open(os.path.join(outdir, "tb_keccak_vecs.vh"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print("reference checked; %d messages, %d blocks written" % (len(plan), len(blocks)))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".")
